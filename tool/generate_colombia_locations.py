#!/usr/bin/env python3
"""Generates lib/core/config/colombia_locations_data.dart from DANE DIVIPOLA.

Source: DANE, "DIVIPOLA - Códigos municipios" (datos.gov.co, dataset gdxc-w37w):
https://www.datos.gov.co/resource/gdxc-w37w.json?$limit=5000
Each row has the department, the municipality and the coordinates of its urban
centre. Run: python3 tool/generate_colombia_locations.py <divipola.json>
"""
import json
import sys
import unicodedata

PARTICLES = {"de", "del", "la", "las", "los", "el", "y", "e", "en", "a"}


def title(name: str) -> str:
    words = name.lower().split(" ")
    out = []
    for index, word in enumerate(words):
        if index > 0 and word in PARTICLES:
            out.append(word)
        elif word == "d.c.":
            out.append("D.C.")
        else:
            out.append(word[:1].upper() + word[1:])
    return " ".join(out)


def department_name(raw: str) -> str:
    if raw.startswith("ARCHIPIÉLAGO DE SAN ANDRÉS"):
        return "San Andrés, Providencia y Santa Catalina"
    return title(raw)


def sort_key(value: str) -> str:
    folded = unicodedata.normalize("NFD", value.lower())
    return "".join(ch for ch in folded if unicodedata.category(ch) != "Mn")


def coordinate(raw: str) -> float:
    return round(float(raw.replace(",", ".")), 4)


def dart_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def main(path: str) -> None:
    rows = json.load(open(path, encoding="utf-8"))
    departments: dict[tuple[str, str], list[tuple[str, str, float, float]]] = {}
    for row in rows:
        key = (row["cod_dpto"], department_name(row["dpto"]))
        departments.setdefault(key, []).append(
            (row["cod_mpio"], title(row["nom_mpio"]), coordinate(row["latitud"]),
             coordinate(row["longitud"])))
    lines = [
        "// GENERATED by tool/generate_colombia_locations.py from DANE DIVIPOLA",
        "// (datos.gov.co, dataset gdxc-w37w). Do not edit by hand.",
        "part of 'colombia_locations.dart';",
        "",
        "const _divipola = <ColombiaDepartment>[",
    ]
    for (code, name), municipalities in sorted(departments.items(), key=lambda item: sort_key(item[0][1])):
        lines.append(f"  ColombiaDepartment({dart_string(code)}, {dart_string(name)}, [")
        for m_code, m_name, lat, lng in sorted(municipalities, key=lambda item: sort_key(item[1])):
            lines.append(
                f"    ColombiaMunicipality({dart_string(m_code)}, {dart_string(m_name)}, {lat}, {lng}),")
        lines.append("  ]),")
    lines.append("];")
    with open("lib/core/config/colombia_locations_data.dart", "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")
    total = sum(len(v) for v in departments.values())
    print(f"{len(departments)} departments, {total} municipalities")


if __name__ == "__main__":
    main(sys.argv[1])
